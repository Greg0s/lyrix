import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename } from "node:path";
import { normalize } from "../src/game/normalize";

/**
 * Writes worker/src/lexiconWords.ts: every word the game knows, so a guess
 * that is no word at all is refused rather than counted (worker/src/lexicon.ts).
 * Made from the French word list of `an-array-of-french-words` (MIT, the
 * Letterpress list: ~336,000 forms, conjugations and plurals included) and
 * the hand-curated worker/lexicon/extra.txt (what songs say and that list
 * leaves out). Embedded in the Worker, so it ships with it and a player's
 * browser never loads it; tests/unit/scripts/buildLexicon.test.ts fails while
 * the module is out of step with its sources.
 *
 *   npm run lexicon:build
 */

export const EXTRA_WORDS = "worker/lexicon/extra.txt";
export const LEXICON_MODULE = "worker/src/lexiconWords.ts";

/** A word's key as a guess's is looked up: normalized, with a plain apostrophe. */
export function lexiconKey(word: string): string {
  return normalize(word.trim()).replace(/[’ʼ]/gu, "'");
}

/** The words of worker/lexicon/extra.txt: one per line, blank lines and # comments left out. */
export function parseExtraWords(text: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
}

/**
 * Every key, sorted in code-unit order (what `<` compares, so a binary search
 * agrees with it). A word holding a hyphen or an apostrophe makes each of its
 * letter runs known too, since the lyrics are tokenized on letters: a song's
 * "rendez-vous" is two words, "rendez" and "vous".
 */
export function lexiconKeys(words: Iterable<string>): string[] {
  const keys = new Set<string>();
  for (const word of words) {
    const key = lexiconKey(word);
    if (key.length === 0) continue;
    keys.add(key);
    if (/['-]/.test(key)) {
      for (const part of key.split(/[^\p{L}\p{N}]+/u)) if (part.length > 0) keys.add(part);
    }
  }
  return [...keys].sort();
}

function frenchWords(): string[] {
  const require = createRequire(import.meta.url);
  const words: unknown = require("an-array-of-french-words");
  if (!Array.isArray(words) || !words.every((word: unknown) => typeof word === "string")) {
    throw new Error("an-array-of-french-words didn't give a list of words: is it installed (npm install)?");
  }
  return words as string[];
}

export function lexiconSource(extra: string = readFileSync(EXTRA_WORDS, "utf8")): string {
  const keys = lexiconKeys([...frenchWords(), ...parseExtraWords(extra)]);
  // A template literal, one word per line: nothing in a key may end it or interpolate.
  const unsafe = keys.find((key) => /[`\\$\s]/.test(key));
  if (unsafe !== undefined) throw new Error(`"${unsafe}" can't be written into the lexicon module`);
  return [
    "// Generated by `npm run lexicon:build` from an-array-of-french-words and worker/lexicon/extra.txt: never edit by hand.",
    "// Every word the game knows, normalized (src/game/normalize.ts), sorted in code-unit order, one per line.",
    `export const LEXICON_SIZE = ${keys.length};`,
    `export const LEXICON = \`\n${keys.join("\n")}\n\`;`,
    "",
  ].join("\n");
}

if (process.argv[1] && basename(process.argv[1]).startsWith("build-lexicon")) {
  writeFileSync(LEXICON_MODULE, lexiconSource());
  console.log(`wrote ${LEXICON_MODULE}`);
}
