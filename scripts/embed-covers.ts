import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

/**
 * Writes worker/src/coverOverrides.ts from worker/covers/*.jpg: the covers
 * the developer supplied by hand for catalog songs Deezer has none for
 * (`npm run covers:check` lists them). Embedded in the Worker as base64, so
 * they ship with it and need no upload step; tests/unit/worker/covers.test.ts
 * fails while the module is out of step with the files.
 *
 *   npm run covers:embed
 */

export const COVERS_DIR = "worker/covers";
export const OVERRIDES_MODULE = "worker/src/coverOverrides.ts";

export function coverOverridesSource(dir: string = COVERS_DIR): string {
  const files = readdirSync(dir)
    .filter((file) => file.endsWith(".jpg"))
    .sort();
  const entries = files.map(
    (file) => `  "${basename(file, ".jpg")}": "${readFileSync(join(dir, file)).toString("base64")}",`
  );
  return [
    "// Generated by `npm run covers:embed` from worker/covers/*.jpg: never edit by hand.",
    "// Covers supplied by hand for catalog songs Deezer has none for, as base64 JPEGs, by catalog id.",
    "export const COVER_OVERRIDES: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && basename(process.argv[1]).startsWith("embed-covers")) {
  writeFileSync(OVERRIDES_MODULE, coverOverridesSource());
  console.log(`wrote ${OVERRIDES_MODULE}`);
}
